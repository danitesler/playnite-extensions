def geometry(bitmap):
    rows = [r for r in bitmap.strip("\n").split("\n")]
    assert len(rows) == 16, len(rows)
    parts = []
    for y, row in enumerate(rows):
        assert len(row) == 16, (y, row)
        for m in re.finditer(r"#+", row):
            x, w = m.start(), m.end() - m.start()
            parts.append(f"M{x},{y}h{w}v1h-{w}z")
    return "".join(parts)


def main():
    text = MEDIA.read_text(encoding="utf-8")
    start, end = "<!-- icons:start -->", "<!-- icons:end -->"
    lines = [f'    <Geometry x:Key="Icon{name}">{geometry(bmp)}</Geometry>' for name, bmp in ICONS.items()]
    block = start + "\n" + "\n".join(lines) + "\n    " + end
    i, j = text.index(start), text.index(end) + len(end)
    MEDIA.write_text(text[:i] + block + text[j:], encoding="utf-8")
    print(f"wrote {len(ICONS)} icons to {MEDIA}")


if __name__ == "__main__":
    main()
