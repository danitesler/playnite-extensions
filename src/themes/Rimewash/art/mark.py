#!/usr/bin/env python3
"""Rimewash mark: a six-armed hoarfrost crystal inside a hand-wobbled ring, nothing else: the gold chevron lives in the UI, not the mark.

Writes art/mark-strokes.svg (the stroke drawing, source of the XAML geometry in Common.xaml and the preview ghost) and
art/mark.svg (the same drawing as filled outlines for scripts/render-addon-icon.ps1, which puts it on the shared orange tile) and
prints the path data used by the previews and by Media.xaml (IconMark, a 24 x 24 geometry of filled shapes).

    python art/mark.py
"""
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))
C = 48.0


def crystal_path(cx, cy, arm, scale=1.0):
    d = []
    for k in range(6):
        a = math.radians(-90 + 60 * k)
        ex, ey = cx + math.cos(a) * arm * scale, cy + math.sin(a) * arm * scale
        d.append("M%.2f,%.2f L%.2f,%.2f" % (cx, cy, ex, ey))
        for t, bl, ang in ((0.50, 0.34, 55), (0.78, 0.22, 55)):
            bx, by = cx + math.cos(a) * arm * t * scale, cy + math.sin(a) * arm * t * scale
            for s in (-1, 1):
                a2 = a + math.radians(s * ang)
                d.append("M%.2f,%.2f L%.2f,%.2f" % (bx, by, bx + math.cos(a2) * arm * bl * scale, by + math.sin(a2) * arm * bl * scale))
    return " ".join(d)


def ring_path(cx, cy, r):
    # a ring with a wobble and a small gap at the bottom right, drawn as one open stroke
    pts = []
    start, end = math.radians(-70), math.radians(250)  # gap from 250deg to 290deg (bottom)
    steps = 72
    for i in range(steps + 1):
        t = start + (end - start) * i / steps
        wob = 1 + 0.012 * math.sin(3 * t + 0.6) + 0.008 * math.sin(7 * t)
        pts.append((cx + r * wob * math.cos(t), cy + r * wob * math.sin(t)))
    return "M" + " L".join("%.2f,%.2f" % p for p in pts)


def chevron_path(cx, cy):
    return "M%.2f,%.2f L%.2f,%.2f L%.2f,%.2f" % (cx - 5, cy - 4.5, cx + 3.5, cy, cx - 5, cy + 4.5)


def outline_svg(paths):
    """Strokes as a union of filled discs (a <circle> every 0.45 units along each segment): render-addon-icon.ps1 fills shapes, it
    does not stroke, and its path fallback XORs overlapping sub-paths, while circles always union. One colour."""
    out = ['<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 96 96" width="96" height="96">',
           '  <!-- Rimewash mark: a wobbled ring and a six-armed hoarfrost crystal. One colour. Generated by art/mark.py (discs along the strokes). -->']
    seen = set()
    for d, w in paths:
        r = w / 2.0
        pen = None
        cmd = "M"
        for tok in d.replace("M", " M ").replace("L", " L ").split():
            if tok in ("M", "L"):
                cmd = tok
                continue
            x, y = [float(v) for v in tok.split(",")]
            pts = [(x, y)]
            if cmd == "L" and pen is not None:
                px, py = pen
                n = max(1, int(math.hypot(x - px, y - py) / 0.45))
                pts = [(px + (x - px) * i / n, py + (y - py) * i / n) for i in range(1, n + 1)]
            for (cx, cy) in pts:
                key = (round(cx, 1), round(cy, 1), r)
                if key in seen:
                    continue
                seen.add(key)
                out.append('  <circle cx="%.2f" cy="%.2f" r="%.2f" fill="#000000"/>' % (cx, cy, r))
            pen = (x, y)
    out.append('</svg>')
    return chr(10).join(out) + chr(10)


if __name__ == "__main__":
    ring = ring_path(C, C - 1, 41)
    cry = crystal_path(C, C - 3, 26)
    chev = chevron_path(C, C + 31)
    nl = chr(10)
    svg = (
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 96 96" fill="none" stroke="#ffffff" '
        'stroke-linecap="round" stroke-linejoin="round">' + nl
        + '  <path d="%s" stroke-width="3.4"/>' + nl
        + '  <path d="%s" stroke-width="3.2"/>' + nl
        + '</svg>' + nl
    ) % (ring, cry)
    open(os.path.join(HERE, "mark-strokes.svg"), "w", encoding="utf-8").write(svg)
    open(os.path.join(HERE, "mark.svg"), "w", encoding="utf-8").write(outline_svg([(ring, 3.4), (cry, 3.2)]))
    print("ring:", ring)
    print("crystal:", cry)
    print("chevron:", chev)
